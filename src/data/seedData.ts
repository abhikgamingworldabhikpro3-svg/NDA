export const seedSampleFirestoreData = async () => {
  const { articleService, questionService } = await import('../services/dbServices');
  try {
    for (const art of sampleArticles) {
      try {
        await articleService.createAdminArticle(art);
      } catch (e) {
        console.warn(`Article write skipped (${art.id}):`, e);
      }
    }
    for (const q of sampleQuestions) {
      try {
        await questionService.saveAdminQuestion(q);
      } catch (e) {
        console.warn(`Question write skipped (${q.id}):`, e);
      }
    }
    console.log("Database seeded successfully with NDA Current Affairs & GK!");
    return true;
  } catch (err) {
    console.warn("Seeding notice:", err);
    return false;
  }
};

export const getCategoriesCount = (articles: CurrentAffair[], questions: Question[]) => {
  const counts: Record<string, { articles: number, questions: number }> = {};
  
  // Set defaults
  const categories = [
    "National", "Defence", "International", "Science & Technology", "Space",
    "Economy", "Government Schemes", "Environment", "Awards", "Sports",
    "Appointments", "Important Days", "Reports & Indexes", "International Organisations",
    "Places in News"
  ];
  categories.forEach(cat => {
    counts[cat] = { articles: 0, questions: 0 };
  });

  articles.forEach(art => {
    if (counts[art.category]) {
      counts[art.category].articles += 1;
    }
  });

  questions.forEach(q => {
    if (counts[q.category]) {
      counts[q.category].questions += 1;
    }
  });

  return counts;
};

export const getRecommendedArticles = (articles: CurrentAffair[], completedIds: string[]) => {
  // Recommend high priority articles that haven't been completed/read yet
  return articles
    .filter(a => !completedIds.includes(a.id))
    .sort((a, b) => {
      const priorityWeight = { HIGH: 3, MEDIUM: 2, LOW: 1 };
      return priorityWeight[b.priority] - priorityWeight[a.priority];
    })
    .slice(0, 3);
};
